BEGIN;
CREATE TABLE IF NOT EXISTS public.worship_interest (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  phone VARCHAR(30),
  interest VARCHAR(20) NOT NULL CHECK (interest IN ('attend','music','volunteer')),
  first_time BOOLEAN NOT NULL,
  consent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updates_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS worship_interest_interest_idx ON public.worship_interest (interest);
CREATE INDEX IF NOT EXISTS worship_interest_created_at_idx ON public.worship_interest (created_at DESC);
COMMIT;
